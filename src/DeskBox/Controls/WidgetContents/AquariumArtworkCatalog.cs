    internal static bool TryGetProfile(string key, out AquariumArtworkProfile profile) => Profiles.TryGetValue(key, out profile);

    internal static double VerticalAnchor(string key, bool animatedCreature) =>
        TryGetProfile(key, out var profile) && profile.IsFloatingPlant ? .3 : animatedCreature ? .5 : 1;

    internal static double DefaultPlacementY(string key, bool fish, int index) =>
        TryGetProfile(key, out var profile) && profile.IsFloatingPlant ? .16 : fish ? .3 + index % 3 * .13 : .88 + index % 2 * .05;

    internal static double ClampPlacementY(string key, bool animatedCreature, double y, double relativeHeight)
    {
        double anchor = VerticalAnchor(key, animatedCreature);
        double minimum = Math.Min(.95, relativeHeight * anchor);
        double maximum = Math.Max(minimum, Math.Min(.98, 1 - relativeHeight * (1 - anchor)));
        return Math.Clamp(y, minimum, maximum);
    }

    internal static string AssetRelativePath(string key) => Profiles.ContainsKey(key)
        ? $"Assets/Aquarium/Vector/{key}.png"
        : $"Assets/Aquarium/{key}.png";
