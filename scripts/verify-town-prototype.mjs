import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const base=new URL('../src/DeskBox/Assets/Tree/TownPrototype/',import.meta.url);
const code=await readFile(new URL('town-rules.js',base),'utf8');
const {validatePlacement,playerCanStand,protectedAreas,intersects,findStandingPosition}=await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const catalog=JSON.parse(await readFile(new URL('catalog.json',base),'utf8'));
const empty={placements:[]}, id=catalog.items[0].id;
assert.equal(catalog.items.length,1500);assert.equal(catalog.terrain_version,5);assert.deepEqual(protectedAreas(catalog),[]);
assert.equal(catalog.map_width,768);assert.equal(catalog.map_height,768);assert.equal(catalog.chunks_x,32);
assert.equal(validatePlacement(catalog,empty,id,96,100),null);
assert.equal(validatePlacement(catalog,empty,id,95,89),null);
assert.notEqual(validatePlacement(catalog,empty,id,64,20),null);
assert.notEqual(validatePlacement(catalog,empty,id,140,30),null);
assert.notEqual(validatePlacement(catalog,empty,id,768,100),null);
assert.equal(validatePlacement(catalog,empty,id,300,300),null);
assert.equal(validatePlacement(catalog,empty,id,600,600),null);
assert.equal(playerCanStand(catalog,empty,95*16+8,89*16+8),true);
assert.equal(playerCanStand(catalog,empty,64*16+8,20*16+8),false);
const existing={placements:[{instance_id:'a',asset_id:'retired-item',tile_x:110,tile_y:100,footprint:{width:4,height:3}}]};
assert.notEqual(validatePlacement(catalog,existing,id,112,101),null);
assert.equal(playerCanStand(catalog,existing,112*16+8,101*16+8),false);
assert.equal(intersects({x:0,y:0,width:1,height:1},{x:1,y:0,width:1,height:1}),false);
const saved={pixel_x:300*16+8.25,pixel_y:300*16+15.5};
assert.deepEqual(findStandingPosition(catalog,empty,saved),{x:saved.pixel_x,y:saved.pixel_y});
const blocked={placements:[{instance_id:'block',asset_id:'retired-item',tile_x:300,tile_y:300,footprint:{width:1,height:1}}]};
const corrected=findStandingPosition(catalog,blocked,saved);
assert.equal(playerCanStand(catalog,blocked,corrected.x,corrected.y),true);
assert.equal(Math.abs(Math.floor(corrected.x/16)-300)+Math.abs(Math.floor(corrected.y/16)-300),1);
assert.equal(playerCanStand(catalog,empty,767*16+8,767*16+15),true);
assert.equal(playerCanStand(catalog,empty,768*16+8,767*16+15),false);
console.log('Shared town map, terrain, footprint and saved-position checks passed');
