import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source = await readFile(new URL('../src/DeskBox/Assets/Tree/TownPrototype/town-realtime.js',import.meta.url),'utf8');
const {mergePresenceDelta,expirePresence,presencePosition,mergeNpcDelta} = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const players = new Map([['far-away',{user_id:'far-away',tile_x:600,tile_y:600}]]);
assert(mergePresenceDelta(players,{sequence:2,player:{user_id:'nearby',tile_x:12,tile_y:20,pixel_x:200.25,pixel_y:335.5,expires_at:'2026-11-11T08:00:30Z'}}));
assert.equal(players.size,2,'A delta must not clear a player in a different neighborhood');
assert.deepEqual(presencePosition(players.get('nearby')),{x:200.25,y:335.5});
assert.equal(mergePresenceDelta(players,{sequence:1,player:{user_id:'nearby',tile_x:1,tile_y:1}}),false,'Old messages cannot move a player backwards');
assert.equal(mergePresenceDelta(players,{sequence:2,player:{user_id:'nearby',tile_x:1,tile_y:1}}),false,'Duplicates are ignored');
assert.equal(mergePresenceDelta(players,{sequence:3,player:{user_id:'nearby',tile_x:'invalid',tile_y:1}}),false);
assert.equal(expirePresence(players,Date.parse('2026-11-11T08:00:20Z')),false);
assert.equal(expirePresence(players,Date.parse('2026-11-11T08:00:31Z')),true);
assert(players.has('far-away'));
assert(!players.has('nearby'));
assert.deepEqual(presencePosition({tile_x:4,tile_y:5}),{x:72,y:96},'Old HTTP servers retain a tile-based fallback');
const npcs = new Map();
assert(mergeNpcDelta(npcs,{npc_id:'npc-1',sequence:4,tile_x:10,tile_y:11,state:'walk',route:[{x:10,y:11},{x:11,y:11}]}));
assert.equal(npcs.get('npc-1').runtime.state,'walk');
assert.equal(mergeNpcDelta(npcs,{npc_id:'npc-1',sequence:3,tile_x:1,tile_y:1,state:'rest'}),false,'Old NPC messages cannot move a character backwards');
assert.equal(mergeNpcDelta(npcs,{npc_id:'npc-1',sequence:4,tile_x:1,tile_y:1,state:'rest'}),false,'Duplicate NPC messages are ignored');
assert(mergeNpcDelta(npcs,{npc_id:'npc-1',sequence:5,tile_x:11,tile_y:11,state:'work'}));
assert.equal(npcs.get('npc-1').runtime.state,'work');
console.log('Town realtime player/NPC delta, pixel interpolation input, ordering and expiry checks passed');
